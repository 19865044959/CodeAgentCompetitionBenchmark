# ============================================================
cur.execute("""
CREATE TABLE 路段 (
    路段id INTEGER PRIMARY KEY,
    路段名 TEXT NOT NULL,
    所属区 TEXT NOT NULL,
    长度km REAL,
    车道数 INTEGER
)
""")

cur.execute("""
CREATE TABLE 摄像头 (
    摄像头id INTEGER PRIMARY KEY,
    所属路段id INTEGER NOT NULL,
    安装日期 TEXT,
    摄像头类型 TEXT,
    运行状态 TEXT,
    FOREIGN KEY (所属路段id) REFERENCES 路段(路段id)
)
""")

cur.execute("""
CREATE TABLE 违章记录 (
    记录id INTEGER PRIMARY KEY,
    摄像头id INTEGER NOT NULL,
    车牌号 TEXT,
    违章类型 TEXT,
    违章时间 TEXT,
    罚款金额元 INTEGER,
    FOREIGN KEY (摄像头id) REFERENCES 摄像头(摄像头id)
)
""")

cur.execute("""
CREATE TABLE 事故记录 (
    事故id INTEGER PRIMARY KEY,
    路段id INTEGER NOT NULL,
    事故类型 TEXT,
    发生时间 TEXT,
    受伤人数 INTEGER,
    处理状态 TEXT,
    FOREIGN KEY (路段id) REFERENCES 路段(路段id)
)
""")

