# 3. 陷阱：创建一个误导 View
#    列名和内容与预期不同，可能让人误入歧途
# ============================================================
cur.execute("""
CREATE VIEW 违章统计 AS
SELECT
    路段.路段名,
    COUNT(*) as 违章次数,
    SUM(违章记录.罚款金额元) as 总罚款
FROM 违章记录
JOIN 摄像头 ON 违章记录.摄像头id = 摄像头.摄像头id
JOIN 路段 ON 摄像头.所属路段id = 路段.路段id
WHERE 违章记录.违章时间 LIKE '2024%'
GROUP BY 路段.路段id
ORDER BY 违章次数 DESC
""")

